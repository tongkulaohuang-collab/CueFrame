import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root=fileURLToPath(new URL('../',import.meta.url));
const sha=value=>createHash('sha256').update(value).digest('hex');
function sourceFiles(folder) {
  return fs.readdirSync(folder,{withFileTypes:true}).flatMap(entry=>{
    const file=path.join(folder,entry.name);
    return entry.isDirectory()?sourceFiles(file):entry.isFile()&&/\.(mjs|json)$/.test(entry.name)?[file]:[];
  });
}
function snapshot(base) {
  return new Map(['server','shared'].flatMap(dir=>sourceFiles(path.join(base,dir))).sort()
    .map(file=>[path.relative(base,file).replaceAll('\\','/'),fs.readFileSync(file)]));
}
const fingerprint=files=>sha([...files].map(([file,bytes])=>file+'\0'+sha(bytes)).join('\n'));

// Capture source and schemas together when this process loads its modules.
// A long-lived worker must not combine cached validators with later disk schemas.
export function captureGenerationRuntime(base=root) {
  const files=snapshot(base),loaded=fingerprint(files);
  const current=()=>fingerprint(snapshot(base))===loaded;
  const assertCurrent=(stage='submit')=>{
    const detail=stage==='apply'?'生成结果已返回并保留，尚未采用；请在当前工作台继续采用和渲染。':
      stage==='segments'?'分段进度与已返回结果已保留；请在当前工作台继续未完成分段。':
      '本次尚未提交生成，请从当前工作台入口继续。';
    if(!current())throw Object.assign(Error('工作台服务已更新，当前进程尚未切换；'+detail),
      {code:'WORKBENCH_RUNTIME_STALE',status:409,stage});
  };
  return {fingerprint:loaded,current,assertCurrent,
    schema(file,destination) {
      assertCurrent();
      const key=path.relative(base,file).replaceAll('\\','/');
      const bytes=files.get(key)||fs.readFileSync(file); // Dynamic schemas are generated by this loaded runtime.
      JSON.parse(bytes.toString('utf8'));
      fs.mkdirSync(path.dirname(destination),{recursive:true});fs.writeFileSync(destination,bytes);
      return {file:destination,sha256:sha(bytes),runtimeFingerprint:loaded};
    }};
}
export const generationRuntime=captureGenerationRuntime();
